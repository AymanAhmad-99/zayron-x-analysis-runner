import { detectPublicLeakage } from './sanitizer';
import type { VulnerabilityEditorialDto } from './editorialDto';
import { validateCrossFieldConsistency } from './consistency';

/**
 * ZAYRON-X Hard Publication Gate
 * 
 * Asserts that a candidate intelligence article satisfies all publishing criteria
 * before public release.
 */

export interface GateResult {
  passed: boolean;
  errors: string[];
  warnings: string[];
}

export function evaluateEditorialPublicationGate(dto: VulnerabilityEditorialDto): GateResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  // 1. Assert Title & Standfirst Hygiene
  const titleLeak = detectPublicLeakage(dto.meta.title);
  if (!titleLeak.passed) errors.push(...titleLeak.violations.map(v => `Title: ${v}`));

  const standfirstLeak = detectPublicLeakage(dto.meta.standfirst);
  if (!standfirstLeak.passed) errors.push(...standfirstLeak.violations.map(v => `Standfirst: ${v}`));

  // 2. Assert Executive Assessment Hygiene
  const execLeak = detectPublicLeakage(dto.executiveAssessment);
  if (!execLeak.passed) errors.push(...execLeak.violations.map(v => `Executive Assessment: ${v}`));

  // 3. Assert Absence of SVG text leaks
  if (/<svg/i.test(dto.meta.title) || /<svg/i.test(dto.executiveAssessment)) {
    errors.push('Literal SVG element text detected in narrative output');
  }

  // 4. Assert Source Integrity & Uniqueness
  const seenUrls = new Set<string>();
  for (const src of dto.sources) {
    if (!src.url.startsWith('https://') && !src.url.startsWith('http://')) {
      errors.push(`Invalid source URL destination: ${src.url}`);
    }
    const normUrl = src.url.trim().replace(/\/+$/, '').toLowerCase();
    if (seenUrls.has(normUrl)) {
      errors.push(`Duplicate source destination URL exposed: "${src.url}"`);
    }
    seenUrls.add(normUrl);

    // Check for label <-> URL mismatches
    if (src.label.includes('CISA') && src.url.includes('nvd.nist.gov')) {
      errors.push(`Mismatched source label and URL: "${src.label}" points to "${src.url}"`);
    }
    if (src.label.includes('NVD') && src.url.includes('cisa.gov')) {
      errors.push(`Mismatched source label and URL: "${src.label}" points to "${src.url}"`);
    }
  }

  // 5. Assert Timeline Ontology (No internal pipeline events & at least one real event)
  const forbiddenTimelineRegex = /(ingest|deduplicat|normaliz|vector|database update|pipeline)/i;
  for (const ev of dto.timeline) {
    if (forbiddenTimelineRegex.test(ev.title) || forbiddenTimelineRegex.test(ev.description)) {
      errors.push(`Internal pipeline event leaked in public timeline: "${ev.title}"`);
    }
  }
  if (dto.timeline.length === 0) {
    errors.push('Publication Gate Violation: Public timeline must contain at least one public intelligence milestone.');
  }

  // 6. Assert Exploitation Semantics
  if (dto.vulnerabilityProfile.exploitStatus === 'ACTIVE_CAMPAIGN_CONFIRMED' && dto.indicators.length === 0) {
    warnings.push('Active campaign confirmed claim lacks accompanying validated threat indicators.');
  }

  // 7. Assert Canonical URL
  if (!dto.meta.canonicalUrl.startsWith('https://zayron-x.co/articles/')) {
    errors.push(`Malformed canonical URL: ${dto.meta.canonicalUrl}`);
  }

  // 8. Assert Cross-Field Intelligence Consistency
  const consistency = validateCrossFieldConsistency(dto);
  if (!consistency.valid) {
    errors.push(...consistency.conflicts);
  }

  // 9. Assert Evidence Integrity & Claim Traceability (when evidence context provided)
  const fullText = [
    dto.executiveAssessment,
    ...dto.keyFindings.map(f => f.detail),
    dto.technicalAssessment.mechanism || '',
    dto.technicalAssessment.preconditions || '',
    dto.technicalAssessment.boundary || '',
    dto.technicalAssessment.exploitationPath || '',
    dto.technicalAssessment.consequence || '',
  ].join(' \n ');

  // 9a. Assert No Internal Metadata Leaks
  const internalTermRegex = /\b(claim_[a-zA-Z0-9_-]+|ev_[a-zA-Z0-9_-]+|evi_[a-zA-Z0-9_-]+|chunk-[a-zA-Z0-9_-]+|ledger_[a-zA-Z0-9_-]+|Telemetry Pipeline|Cloudflare Edge Telemetry|In Setup|Generated by AI)\b/i;
  if (internalTermRegex.test(fullText) || internalTermRegex.test(dto.meta.title)) {
    errors.push('Internal metadata or pipeline identifier leaked into public article text.');
  }

  // 9b. Assert IOC separation: Recommended detection patterns must not become IOC entries
  for (const ioc of dto.indicators) {
    if (/^(inspect|monitor|audit|review|check)\b/i.test(ioc.value)) {
      errors.push(`Detection guidance leaked into IOC items: "${ioc.value}"`);
    }
  }

  // 9c. Assert Exploitation Semantics: CISA KEV alone must not claim "active campaign" or "weaponized exploit"
  if (dto.vulnerabilityProfile.exploitStatus === 'KNOWN_EXPLOITED_EXTERNAL') {
    if (/\b(active campaign|weaponized exploit|mass exploitation|widespread attacks)\b/i.test(fullText)) {
      errors.push('Exploitation Integrity Violation: CISA KEV status promoted to "active campaign" or "weaponized exploit" without supporting primary evidence.');
    }
  }

  return {
    passed: errors.length === 0,
    errors,
    warnings,
  };
}
