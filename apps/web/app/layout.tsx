export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <link
          rel="alternate"
          type="application/rss+xml"
          title="ZAYRON-X Intelligence Newsroom"
          href="/news/rss.xml"
        />
      </head>
      <body>
        {children}
        {/* Site-wide entity graph. Inline JSON-LD is permitted by the CSP
            (`script-src 'self' 'unsafe-inline'`) and serialized so a `<` can
            never terminate the script element. */}
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: serializeJsonLd(buildSiteJsonLdGraph({ siteUrl: getSiteUrl() })) }}
        />
      </body>
    </html>
  );
}
