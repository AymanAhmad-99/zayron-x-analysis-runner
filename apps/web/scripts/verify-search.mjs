import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const requests = [];
page.on("request", (request) => { if (request.url().includes("/api/v1/search")) requests.push(request.url()); });
await page.goto(process.env.SEARCH_URL ?? "http://127.0.0.1:8787", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Search/ }).click();
const input = page.getByRole("textbox", { name: "Search intelligence" });
await input.fill("vulnerability");
await page.waitForTimeout(700);
const openedFromNavbar = await page.getByRole("dialog").isVisible();
const requestExecuted = requests.some((url) => url.includes("q=vulnerability"));
await page.keyboard.press("Escape");
const closedWithEscape = !(await page.getByRole("dialog").isVisible());
await page.getByRole("button", { name: /Search/ }).click();
const sameUiFromSecondEntry = await page.getByRole("dialog").isVisible() && await page.getByRole("textbox", { name: "Search intelligence" }).isVisible();
await page.screenshot({ path: "D:/Temp/zayron-search-verification/search-overlay-desktop-1440x1000.png", fullPage: false });
await browser.close();
console.log(JSON.stringify({ openedFromNavbar, requestExecuted, closedWithEscape, sameUiFromSecondEntry, requests }, null, 2));
if (!openedFromNavbar || !requestExecuted || !closedWithEscape || !sameUiFromSecondEntry) process.exit(1);
