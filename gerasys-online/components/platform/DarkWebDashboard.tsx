function sanitizeTeaserText(text: string | null): string {
  if (!text) {
    return "Intelligence telemetry captured. Relational threat analysis is being generated by the decentralized agent network.";
  }
  
  let clean = text;
  
  // 1. Remove markdown code blocks and inline code
  clean = clean.replace(/```[\s\S]*?```/g, "");
  clean = clean.replace(/`[^`]*`/g, "");
  
  // 2. Remove JSON-like curly braces and content inside if it looks like JSON
  clean = clean.replace(/\{[^{}]*\}/g, "");
  
  // 3. Remove hashes: hex strings of length 32 (md5), 40 (sha1), 64 (sha256)
  clean = clean.replace(/\b[a-fA-F0-9]{32,64}\b/g, "");
  clean = clean.replace(/\[?HASH:\s*[a-fA-F0-9]+\]?/gi, "");
  
  // 4. Remove URLs
  clean = clean.replace(/https?:\/\/\S+/gi, "");
  clean = clean.replace(/\b\S+\.onion\b/gi, "");
  
  // 5. Clean up any leftover markdown indicators or special characters
  clean = clean.replace(/[#*_\-[\]]/g, "");
  
  // 6. Clean up whitespace
  clean = clean.replace(/\s+/g, " ").trim();
  
  // 7. Limit to 40 words
  const words = clean.split(/\s+/);
  if (words.length > 40) {
    return words.slice(0, 40).join(" ") + "...";
  }
  
  return clean;
}

